"""Шаг 10: приоритизация рекомендаций по объяснимой формуле (FR-16, docs/architecture.md).

P = охват × доля негатива × K / сложность

- охват — доля отзывов своего товара, где встречается проблема (шаг 6);
- доля негатива — среди упоминаний атрибута проблемы (шаг 5);
- K = 1,5, если у конкурентов проблема встречается заметно реже (это отставание
  от рынка, а не свойство категории), иначе 1. Пока нет шага 7, K всегда 1;
- сложность — оценка генератора от 1 (карточка товара) до 3 (сам товар).

Чем чаще проблема, тем сильнее недовольство и тем проще исправление, тем выше
приоритет. Значение K подбирается на этапе тестирования.
"""
from __future__ import annotations

from dataclasses import dataclass

from review_agent.pipeline.issues import Проблема
from review_agent.pipeline.recommend import Рекомендация

K_ОТСТАВАНИЕ = 1.5


@dataclass
class Приоритетная:
    """Рекомендация с приоритетом и данными, из которых он сложился (для отчёта)."""
    recommendation: Рекомендация
    coverage: float
    negative_share: float          # использованное в формуле значение
    negative_share_known: bool     # False: доли негатива нет, взята 1,0
    behind_competitors: bool
    priority: float


def приоритет(охват: float, доля_негатива: float, сложность: int, *,
              отставание: bool = False, k: float = K_ОТСТАВАНИЕ) -> float:
    """P = охват × доля негатива × K / сложность, округление до 4 знаков."""
    if сложность not in (1, 2, 3):
        raise ValueError(f"сложность должна быть 1, 2 или 3, получено {сложность}")
    if not (0 <= охват <= 1 and 0 <= доля_негатива <= 1):
        raise ValueError("охват и доля негатива должны быть от 0 до 1")
    return round(охват * доля_негатива * (k if отставание else 1.0) / сложность, 4)


def расставить(рекомендации: list[Рекомендация], проблемы: list[Проблема], *,
               доли_негатива: dict[str, float] | None = None,
               отставание: dict[str, bool] | None = None,
               k: float = K_ОТСТАВАНИЕ) -> list[Приоритетная]:
    """Считает приоритеты и сортирует по убыванию.

    доли_негатива и отставание — по названию атрибута. Если доли негатива для
    атрибута нет (не передан aggregate.csv), берётся 1,0 и это отмечается:
    тогда порядок определяют только охват и сложность.
    Рекомендация без своей проблемы сюда попадать не должна: её отсекает шаг 11.
    """
    доли_негатива = доли_негатива or {}
    отставание = отставание or {}
    по_ключу = {(п.attribute, п.title): п for п in проблемы}
    итог: list[Приоритетная] = []
    for рек in рекомендации:
        проблема = по_ключу.get((рек.attribute, рек.problem))
        if проблема is None:
            raise ValueError(f"нет проблемы «{рек.problem}»: сначала нужна проверка опоры (шаг 11)")
        известна = рек.attribute in доли_негатива
        доля = доли_негатива.get(рек.attribute, 1.0)
        отстаёт = отставание.get(рек.attribute, False)
        итог.append(Приоритетная(
            recommendation=рек, coverage=проблема.coverage, negative_share=доля,
            negative_share_known=известна, behind_competitors=отстаёт,
            priority=приоритет(проблема.coverage, доля, рек.effort, отставание=отстаёт, k=k)))
    # при равном приоритете выше та, что проще, затем по алфавиту: порядок воспроизводим
    итог.sort(key=lambda п: (-п.priority, п.recommendation.effort, п.recommendation.problem,
                             п.recommendation.action))
    return итог
