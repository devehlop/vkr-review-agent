"""Шаг 11: проверка опоры рекомендаций на отзывы, без LLM (FR-17, docs/architecture.md).

Последняя проверка перед отчётом. Её делает код, поэтому она не зависит от того,
как повела себя модель на шагах 6–9. Рекомендация отклоняется, если:
- она ссылается на проблему, которой нет в результатах шага 6;
- проблема опирается меньше чем на мин_отзывов отзывов, которые есть в выгрузке;
- у рекомендации нет цитат;
- фрагмент цитаты не входит ни в одну цитату проблемы;
- цитата проблемы не находится в тексте ни одного из её отзывов.

Шаг 8 уже сверяет фрагменты с цитатами проблемы. Здесь проверка повторяется и
доводится до исходного текста отзывов: так ошибка на любом предыдущем шаге
не пропустит в отчёт вывод, которого нет в отзывах.
"""
from __future__ import annotations

import re
from dataclasses import dataclass

from review_agent.ingest.loader import Отзыв
from review_agent.pipeline.issues import Проблема
from review_agent.pipeline.recommend import Рекомендация

МИН_ОТЗЫВОВ = 3   # тот же минимум, что и для проблемы на шаге 6


@dataclass
class Отказ:
    """Рекомендация, отклонённая проверкой опоры. Попадает в журнал, а не в отчёт."""
    problem: str
    action: str
    reason: str


def _ключ(текст: str) -> str:
    """Текст для сравнения: без регистра, «ё» как «е», пробелы схлопнуты, края без знаков."""
    return re.sub(r"\s+", " ", текст.lower().replace("ё", "е")).strip(" .,!?;:«»\"'")


def _текст_отзыва(отзыв: Отзыв) -> str:
    return _ключ(" ".join(ч for ч in (отзыв.text, отзыв.pros, отзыв.cons) if ч))


def причина_отказа(рек: Рекомендация, проблема: Проблема | None,
                   отзывы: dict[str, Отзыв], мин_отзывов: int = МИН_ОТЗЫВОВ) -> str | None:
    """None, если рекомендация опирается на отзывы; иначе причина отказа."""
    if проблема is None:
        return f"проблемы «{рек.problem}» ({рек.attribute}) нет в результатах шага 6"
    найденные = [отзывы[i] for i in проблема.review_ids if i in отзывы]
    if len(найденные) < мин_отзывов:
        return (f"проблема опирается на {len(найденные)} отзывов из выгрузки, "
                f"нужно не меньше {мин_отзывов}")
    if not рек.quotes:
        return "у рекомендации нет цитат"
    тексты = [_текст_отзыва(о) for о in найденные]
    цитаты_проблемы = [_ключ(ц) for ц in проблема.quotes]
    for фрагмент in рек.quotes:
        ключ = _ключ(фрагмент)
        источники = [ц for ц in цитаты_проблемы if ключ and ключ in ц]
        if not источники:
            return f"фрагмента «{фрагмент}» нет в цитатах проблемы"
        if not any(ц in т for ц in источники for т in тексты):
            return f"цитаты с фрагментом «{фрагмент}» нет в тексте отзывов проблемы"
    return None


def проверить_опору(рекомендации: list[Рекомендация], проблемы: list[Проблема],
                    отзывы: list[Отзыв], *, мин_отзывов: int = МИН_ОТЗЫВОВ
                    ) -> tuple[list[Рекомендация], list[Отказ]]:
    """Делит рекомендации на прошедшие проверку и отклонённые."""
    по_ключу = {(п.attribute, п.title): п for п in проблемы}
    по_id = {о.id: о for о in отзывы}
    прошли: list[Рекомендация] = []
    отказы: list[Отказ] = []
    for рек in рекомендации:
        причина = причина_отказа(рек, по_ключу.get((рек.attribute, рек.problem)), по_id, мин_отзывов)
        if причина is None:
            прошли.append(рек)
        else:
            отказы.append(Отказ(рек.problem, рек.action, причина))
    return прошли, отказы
