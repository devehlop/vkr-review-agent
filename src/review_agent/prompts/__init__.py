"""Промпты лежат в отдельных файлах с номером версии в имени (NFR-5):
taxonomy_v1.md, extract_v1.md и т. д. Менять промпт = новый файл с новой версией,
чтобы результаты прогонов можно было воспроизвести."""
from pathlib import Path

_ПАПКА = Path(__file__).parent


def загрузить_промпт(имя: str) -> str:
    """Читает промпт по имени без расширения, например «taxonomy_v1»."""
    return (_ПАПКА / f"{имя}.md").read_text(encoding="utf-8")
