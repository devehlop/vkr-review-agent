"""Поиск и скрытие персональных данных в текстах отзывов (NFR-7, ТЗ по ГОСТ 4.1.9).

Покупатели иногда оставляют в отзывах телефоны, почту, ссылки и номера заказов.
Такие фрагменты заменяются метками вида [ТЕЛЕФОН]. Имена и адреса регулярными
выражениями надёжно не находятся: это ограничение фиксируется в тексте ВКР.

Перенесено из PR #2 (сессия 19.11.2026), имена функций приведены к стилю пакета.
"""
from __future__ import annotations

import re

# Порядок важен: сначала почта и ссылки, потом телефоны, потом длинные числа
_ШАБЛОНЫ: list[tuple[str, re.Pattern[str]]] = [
    ("[EMAIL]", re.compile(r"[\w.+-]+@[\w-]+(?:\.[\w-]+)+")),
    ("[ССЫЛКА]", re.compile(r"(?:https?://|www\.)\S+", re.IGNORECASE)),
    # Российские номера: +7 или 8, затем 10 цифр с любыми разделителями
    ("[ТЕЛЕФОН]",
     re.compile(r"(?<!\d)(?:\+7|8)[\s\-()]*\d{3}[\s\-()]*\d{3}[\s\-]*\d{2}[\s\-]*\d{2}(?!\d)")),
    # Номера заказов, треков, карт: восемь и более цифр подряд
    ("[НОМЕР]", re.compile(r"(?<!\d)\d{8,}(?!\d)")),
    # Упоминания аккаунтов в соцсетях
    ("[АККАУНТ]", re.compile(r"(?<![\w.])@[A-Za-z0-9_]{3,}")),
]


def найти_пд(текст: str) -> list[str]:
    """Возвращает метки найденных персональных данных (с повторами)."""
    найдено: list[str] = []
    for метка, шаблон in _ШАБЛОНЫ:
        найдено.extend(метка for _ in шаблон.finditer(текст))
        текст = шаблон.sub(метка, текст)
    return найдено


def есть_пд(текст: str) -> bool:
    return bool(найти_пд(текст))


def скрыть_пд(текст: str) -> str:
    """Заменяет персональные данные метками."""
    for метка, шаблон in _ШАБЛОНЫ:
        текст = шаблон.sub(метка, текст)
    return текст
