"""Тесты шагов 10–11: проверка опоры на отзывы и приоритизация. LLM не нужна."""
import pytest

from review_agent.ingest.loader import Отзыв
from review_agent.pipeline.grounding import проверить_опору
from review_agent.pipeline.issues import Проблема
from review_agent.pipeline.prioritize import приоритет, расставить
from review_agent.pipeline.recommend import Рекомендация

ОТЗЫВЫ = [
    Отзыв("r1", "Куртка", True, text="Маломерит на целый размер, пришлось менять."),
    Отзыв("r2", "Куртка", True, cons="Брала M, а пришло как S"),
    Отзыв("r3", "Куртка", True, text="Размер меньше, чем в таблице"),
    Отзыв("r4", "Куртка", True, text="Ёлки, маломерит!"),
    Отзыв("r5", "Куртка", True, cons="Коробка помята"),
    Отзыв("r6", "Куртка", True, cons="Коробка порвана при доставке"),
]
РАЗМЕР = Проблема(
    attribute="Размер и посадка", title="Маломерит", mentions=4, reviews=4, coverage=0.4,
    quotes=["Маломерит на целый размер, пришлось менять.", "Брала M, а пришло как S",
            "Размер меньше, чем в таблице"], review_ids=["r1", "r2", "r3", "r4"])
УПАКОВКА = Проблема(
    attribute="Упаковка", title="Мятая коробка", mentions=2, reviews=2, coverage=0.2,
    quotes=["Коробка помята", "Коробка порвана при доставке"], review_ids=["r5", "r6"])


def рек(проблема=РАЗМЕР, action="Указать в карточке, что модель маломерит", effort=1,
        quotes=("маломерит на целый размер",)):
    return Рекомендация(problem=проблема.title, attribute=проблема.attribute, action=action,
                        type="карточка товара", rationale="жалобы", expected_effect="",
                        effort=effort, quotes=list(quotes), review_ids=list(проблема.review_ids))


# --- шаг 11 ---
def test_опора_принимает_цитату_из_отзыва_без_учёта_регистра_и_ё():
    прошли, отказы = проверить_опору([рек(quotes=["МАЛОМЕРИТ на целый размер", "пришло как S"])],
                                     [РАЗМЕР], ОТЗЫВЫ)
    assert len(прошли) == 1 and отказы == []


@pytest.mark.parametrize("рекомендация, проблемы, отзывы, причина", [
    (рек(quotes=["нитки гнилые"]), [РАЗМЕР], ОТЗЫВЫ, "нет в цитатах проблемы"),
    (рек(quotes=[]), [РАЗМЕР], ОТЗЫВЫ, "нет цитат"),
    (рек(), [], ОТЗЫВЫ, "нет в результатах шага 6"),
    (рек(УПАКОВКА, "Сменить коробку", 2, ["Коробка помята"]), [УПАКОВКА], ОТЗЫВЫ,
     "опирается на 2 отзывов"),
    # отзывы проблемы не загружены (другой файл): опоры в выгрузке нет
    (рек(), [РАЗМЕР], ОТЗЫВЫ[4:], "опирается на 0 отзывов"),
])
def test_опора_отклоняет(рекомендация, проблемы, отзывы, причина):
    прошли, отказы = проверить_опору([рекомендация], проблемы, отзывы)
    assert прошли == [] and len(отказы) == 1 and причина in отказы[0].reason
    assert отказы[0].action == рекомендация.action


def test_опора_ловит_цитату_проблемы_которой_нет_в_отзывах():
    """Цитата проблемы испорчена на шаге 6: фрагмент совпал с ней, но в отзывах такого текста нет."""
    испорченная = Проблема(**{**РАЗМЕР.__dict__, "quotes": ["Маломерит и линяет"]})
    прошли, отказы = проверить_опору([рек(quotes=["Маломерит"])], [испорченная], ОТЗЫВЫ)
    assert прошли == [] and "нет в тексте отзывов" in отказы[0].reason


# --- шаг 10 ---
def test_формула_приоритета():
    assert приоритет(0.4, 0.5, 1) == 0.2
    assert приоритет(0.4, 0.5, 2) == 0.1
    assert приоритет(0.4, 0.5, 1, отставание=True) == 0.3
    assert приоритет(0.4, 0.5, 1, отставание=True, k=2.0) == 0.4
    with pytest.raises(ValueError, match="сложность"):
        приоритет(0.4, 0.5, 0)
    with pytest.raises(ValueError, match="от 0 до 1"):
        приоритет(1.5, 0.5, 1)


def test_расставить_сортирует_и_учитывает_данные():
    упаковка = Проблема(**{**УПАКОВКА.__dict__, "coverage": 0.3})
    рекомендации = [
        рек(action="Сменить поставщика ткани", effort=3),                       # 0,4×0,8/3
        рек(упаковка, "Перейти на жёсткую коробку", 2, ["Коробка помята"]),     # 0,3×1,0×1,5/2
        рек(action="Указать в карточке, что модель маломерит", effort=1),      # 0,4×0,8/1
    ]
    итог = расставить(рекомендации, [РАЗМЕР, упаковка],
                      доли_негатива={"Размер и посадка": 0.8, "Упаковка": 1.0},
                      отставание={"Упаковка": True})
    assert [п.recommendation.action for п in итог] == [
        "Указать в карточке, что модель маломерит", "Перейти на жёсткую коробку",
        "Сменить поставщика ткани"]
    assert [п.priority for п in итог] == [0.32, 0.225, 0.1067]
    assert итог[1].behind_competitors and not итог[0].behind_competitors


def test_расставить_без_доли_негатива_берёт_единицу_и_отмечает():
    итог = расставить([рек()], [РАЗМЕР])
    assert итог[0].priority == 0.4 and итог[0].negative_share == 1.0
    assert not итог[0].negative_share_known


def test_расставить_при_равном_приоритете_выше_простая():
    a = рек(action="Б-действие", effort=1)
    b = рек(action="А-действие", effort=1)
    итог = расставить([a, b], [РАЗМЕР], доли_негатива={"Размер и посадка": 0.5})
    assert [п.recommendation.action for п in итог] == ["А-действие", "Б-действие"]


def test_расставить_требует_проверки_опоры():
    with pytest.raises(ValueError, match="шаг 11"):
        расставить([рек()], [])
