"""Тесты предобработки отзывов."""
from review_agent.ingest.loader import Отзыв
from review_agent.preprocess.cleaner import (нормализовать, найти_подозрительные,
                                             предобработать, разбить_на_предложения)


def отзыв(id, text="", pros="", cons="", product="Куртка", is_own=True):
    return Отзыв(id=id, product=product, is_own=is_own, text=text, pros=pros, cons=cons)


def test_нормализация_убирает_служебные_символы():
    assert нормализовать("Хорошая​  куртка \x07!") == "Хорошая куртка !"


def test_пустые_и_дубликаты_удаляются():
    отзывы = [отзыв("1", "Хорошая куртка, села идеально."),
              отзыв("2", "хорошая   куртка, села идеально!!"),   # тот же текст
              отзыв("3", "  ​ "),                            # пустой
              отзыв("4", "Маломерит, пришлось менять.")]
    р = предобработать(отзывы)
    assert [o.id for o in р.reviews] == ["1", "4"]
    assert р.stats["empty_removed"] == 1 and р.stats["duplicates_removed"] == 1


def test_одинаковый_текст_у_разных_товаров_не_дубликат():
    р = предобработать([отзыв("1", "Отличное качество пошива, рекомендую.", product="Своя"),
                        отзыв("2", "Отличное качество пошива, рекомендую.", product="Чужая", is_own=False)])
    assert len(р.reviews) == 2


def test_предложения_сохраняют_источник():
    о = отзыв("1", text="Доставили быстро.", pros="Мягкая ткань. Красивый цвет.", cons="Маломерит.")
    п = разбить_на_предложения(о)
    assert [(x.source, x.text) for x in п] == [
        ("pros", "Мягкая ткань."), ("pros", "Красивый цвет."),
        ("cons", "Маломерит."), ("text", "Доставили быстро.")]
    assert [x.idx for x in п] == [0, 1, 2, 3]


def test_знаки_препинания_не_предложение():
    assert разбить_на_предложения(отзыв("1", text="... !!!")) == []


def test_подозрительные_почти_одинаковые_тексты():
    база = "Очень хорошая куртка быстро доставили всем рекомендую советую покупать"
    отзывы = [отзыв("1", база + " сегодня"), отзыв("2", база + " сейчас"),
              отзыв("3", "Молния сломалась через неделю, возврат оформил с трудом")]
    assert найти_подозрительные(отзывы, порог=0.6) == {"1", "2"}


def test_короткие_отзывы_не_подозрительные():
    assert найти_подозрительные([отзыв("1", "Супер!"), отзыв("2", "Супер!!")]) == set()


def test_подозрительные_не_удаляются():
    база = "Очень хорошая куртка быстро доставили всем рекомендую советую покупать"
    р = предобработать([отзыв("1", база + " сегодня"), отзыв("2", база + " сейчас")], порог_сходства=0.6)
    assert len(р.reviews) == 2 and р.suspicious_ids == {"1", "2"}


def test_исходные_отзывы_не_меняются():
    о = отзыв("1", "Хорошая​ куртка")
    предобработать([о])
    assert о.text == "Хорошая​ куртка"
