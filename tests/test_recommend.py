"""Тесты шагов 8–9 на заглушке модели: генератор, проверка цитат, цикл с критиком."""
import json

from review_agent.llm.base import FakeLLMClient
from review_agent.llm.gateway import LLMGateway
from review_agent.pipeline.critic import рекомендации_по_проблемам
from review_agent.pipeline.issues import Проблема
from review_agent.pipeline.recommend import Контекст, проверить_цитаты, сгенерировать

ПРОБЛЕМА = Проблема(
    attribute="Размер и посадка", title="Маломерит на размер", mentions=4, reviews=4,
    coverage=0.2, quotes=["Маломерит на целый размер", "Брала M, а пришло как S",
                          "Размер меньше, чем в таблице"],
    review_ids=["r1", "r2", "r3", "r4"])
ВТОРАЯ = Проблема(
    attribute="Упаковка", title="Мятая коробка", mentions=3, reviews=3, coverage=0.15,
    quotes=["Коробка помята", "Коробка порвана при доставке"], review_ids=["r5", "r6", "r7"])


def рек(action="Указать в карточке, что модель маломерит, и советовать брать на размер больше",
        n=1, text="маломерит на целый размер", тип="карточка товара", effort=1):
    return {"action": action, "type": тип, "rationale": "Жалобы в 20 % отзывов",
            "expected_effect": "Меньше возвратов", "effort": effort,
            "quotes": [{"n": n, "text": text}]}


def ответ_генератора(*рекомендации):
    return json.dumps({"recommendations": list(рекомендации)}, ensure_ascii=False)


def ответ_критика(оценка=5, comment=""):
    return json.dumps({"scores": {"specificity": оценка, "grounding": 5, "feasibility": 5,
                                  "novelty": 5}, "comment": comment}, ensure_ascii=False)


def шлюз(*ответы):
    клиент = FakeLLMClient(list(ответы))
    return LLMGateway(клиент, max_retries=1, sleep=lambda _: None), клиент


def контекст(п=ПРОБЛЕМА):
    return Контекст(п, "женская одежда", 20, negative_share=0.6)


def test_цитаты_проверяются_по_номеру_и_тексту():
    верные, отброшено = проверить_цитаты(
        [{"n": 1, "text": "МАЛОМЕРИТ  на целый"},      # регистр и пробелы не важны
         {"n": 2, "text": "маломерит"},                # нет в цитате № 2
         {"n": 9, "text": "Коробка"},                  # нет такого номера
         {"n": 3, "text": "Размер меньше, чем в таблице."}],
        ПРОБЛЕМА.quotes)
    assert верные == ["МАЛОМЕРИТ  на целый", "Размер меньше, чем в таблице."]
    assert отброшено == 2


def test_генератор_отбрасывает_рекомендацию_без_настоящих_цитат():
    g, клиент = шлюз(ответ_генератора(рек(), рек(action="Сменить фабрику пошива полностью",
                                               text="выдуманная цитата", тип="товар", effort=3)))
    итог = сгенерировать(g, контекст())
    assert len(итог) == 1
    р = итог[0]
    assert р.type == "карточка товара" and р.quotes == ["маломерит на целый размер"]
    assert р.review_ids == ["r1", "r2", "r3", "r4"] and р.problem == "Маломерит на размер"
    промпт = клиент.calls[0][0].content
    assert "60%" in промпт and "4 отзывах из 20" in промпт and "1. Маломерит на целый размер" in промпт


def test_критик_пропускает_хорошую_рекомендацию():
    g, _ = шлюз(ответ_генератора(рек()), ответ_критика(5))
    итог = рекомендации_по_проблемам(g, [ПРОБЛЕМА], категория="одежда", всего_отзывов=20,
                                     количество=1)
    assert len(итог.accepted) == 1 and not итог.rejected
    assert итог.accepted[0].verdicts[0].passed
    assert итог.stats["revisions"] == 0


def test_доработка_по_замечаниям_критика():
    исправленная = рек(action="Добавить в карточку таблицу замеров изделия в сантиметрах")
    g, клиент = шлюз(ответ_генератора(рек(action="Улучшить размер")),
                     ответ_критика(2, "Слишком общо"),
                     ответ_генератора(исправленная), ответ_критика(5))
    итог = рекомендации_по_проблемам(g, [ПРОБЛЕМА], категория="одежда", всего_отзывов=20,
                                     количество=1)
    assert len(итог.accepted) == 1
    принятая = итог.accepted[0]
    assert принятая.recommendation.action.startswith("Добавить в карточку таблицу")
    assert [в.passed for в in принятая.verdicts] == [False, True]
    # замечания критика переданы генератору
    assert "Слишком общо" in клиент.calls[2][0].content
    assert итог.stats["revisions"] == 1


def test_после_двух_доработок_рекомендация_отклоняется_а_проблема_остаётся():
    ответы = [ответ_генератора(рек())]
    for _ in range(2):
        ответы += [ответ_критика(2, "Плохо"), ответ_генератора(рек())]
    ответы.append(ответ_критика(2, "Плохо"))
    g, _ = шлюз(*ответы)
    итог = рекомендации_по_проблемам(g, [ПРОБЛЕМА], категория="одежда", всего_отзывов=20,
                                     количество=1)
    assert not итог.accepted and len(итог.rejected) == 1
    assert len(итог.rejected[0].verdicts) == 3
    assert итог.rejected[0].reason == "не прошла проверку после доработок"
    assert итог.problems_without_recommendation == ["Маломерит на размер"]


def test_критик_не_ответил_рекомендация_не_принимается():
    g, _ = шлюз(ответ_генератора(рек()), "это не JSON")
    итог = рекомендации_по_проблемам(g, [ПРОБЛЕМА], категория="одежда", всего_отзывов=20,
                                     количество=1)
    assert not итог.accepted
    assert итог.rejected[0].reason.startswith("критик не ответил")


def test_сбой_генератора_не_роняет_остальные_проблемы():
    g, _ = шлюз("сломанный ответ",
                ответ_генератора(рек(action="Упаковывать в жёсткую коробку вместо пакета",
                                     n=1, text="Коробка помята", тип="упаковка", effort=2)),
                ответ_критика(5))
    итог = рекомендации_по_проблемам(g, [ПРОБЛЕМА, ВТОРАЯ], категория="одежда",
                                     всего_отзывов=20, количество=1)
    assert итог.stats["generator_failed"] == 1
    assert [п.recommendation.problem for п in итог.accepted] == ["Мятая коробка"]
    assert итог.problems_without_recommendation == ["Маломерит на размер"]


def test_принятые_рекомендации_передаются_критику_для_проверки_повторов():
    g, клиент = шлюз(ответ_генератора(рек()), ответ_критика(5),
                     ответ_генератора(рек(action="Упаковывать в жёсткую коробку вместо пакета",
                                          text="Коробка помята", тип="упаковка")),
                     ответ_критика(5))
    рекомендации_по_проблемам(g, [ПРОБЛЕМА, ВТОРАЯ], категория="одежда", всего_отзывов=20,
                              количество=1)
    assert "пока нет" in клиент.calls[1][0].content
    assert "- Указать в карточке, что модель маломерит" in клиент.calls[3][0].content


def test_режим_без_критика_принимает_все_черновики():
    g, клиент = шлюз(ответ_генератора(рек(), рек(action="Добавить таблицу замеров в см",
                                               n=3, text="меньше, чем в таблице")))
    итог = рекомендации_по_проблемам(g, [ПРОБЛЕМА], категория="одежда", всего_отзывов=20,
                                     с_критиком=False)
    assert len(итог.accepted) == 2 and len(клиент.calls) == 1
    assert итог.stats["critic"] is False
