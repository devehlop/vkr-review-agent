"""Тесты рекомендаций по сильным сторонам (вторая часть FR-13) на заглушке модели."""
import json

from review_agent.llm.base import FakeLLMClient
from review_agent.llm.gateway import LLMGateway
from review_agent.pipeline.aggregate import СтатАспекта
from review_agent.pipeline.extract import Упоминание
from review_agent.pipeline.strengths import найти_сильные_стороны, рекомендации_по_сильным_сторонам


def упоминание(i, текст, тема="Материал и фактура", тон="positive", свой=True):
    return Упоминание(review_id=f"r{i}", sentence_idx=0, attribute=тема, sentiment=тон, source="pros",
                      text=текст, product="Куртка" if свой else "Конкурент", is_own=свой)


def стат(тема, упоминаний, позитив, охват=0.3, свой=True):
    return СтатАспекта(product="Куртка" if свой else "Конкурент", is_own=свой, attribute=тема,
                       mentions=упоминаний, reviews=упоминаний, coverage=охват, positive=позитив,
                       negative=упоминаний - позитив)


УПОМИНАНИЯ = [упоминание(1, "Ткань мягкая и приятная"), упоминание(2, "ткань мягкая и приятная!"),
              упоминание(3, "Материал не колется"), упоминание(4, "Ткань тонкая", тон="negative")]


def рек(text="Ткань мягкая и приятная", n=1,
        action="Добавить в заголовок и первую строку описания: «мягкая ткань, не колется»"):
    return json.dumps({"recommendations": [{
        "action": action,
        "type": "карточка товара", "rationale": "Ткань хвалят в 30 % отзывов",
        "expected_effect": "Покупатель сразу видит главное достоинство", "effort": 1,
        "quotes": [{"n": n, "text": text}]}]}, ensure_ascii=False)


def критик(оценка=5, comment=""):
    return json.dumps({"scores": {"specificity": оценка, "grounding": 5, "feasibility": 5, "novelty": 5},
                       "comment": comment}, ensure_ascii=False)


def шлюз(*ответы):
    клиент = FakeLLMClient(list(ответы))
    return LLMGateway(клиент, max_retries=1, sleep=lambda _: None), клиент


def test_отбор_сильных_сторон():
    статистика = [стат("Материал и фактура", 4, 3), стат("Доставка", 5, 4, охват=0.5),
                  стат("Цвет и оттенок", 5, 2), стат("Фурнитура", 2, 2),
                  стат("Упаковка", 9, 9, свой=False)]
    стороны = найти_сильные_стороны(статистика, УПОМИНАНИЯ, исключить={"Доставка"})
    # Доставка исключена (есть проблема), цвет чаще ругают, фурнитуры мало, упаковка у конкурента
    assert [(т.attribute, round(доля, 2)) for т, доля in стороны] == [("Материал и фактура", 0.75)]
    тема = стороны[0][0]
    assert тема.quotes == ["Ткань мягкая и приятная", "Материал не колется"]
    assert тема.review_ids == ["r1", "r2", "r3"]


def test_тема_с_проблемой_не_становится_сильной_стороной():
    статистика = [стат("Доставка", 10, 8)]
    assert найти_сильные_стороны(статистика, [], исключить={"Доставка"}) == []
    assert len(найти_сильные_стороны(статистика, [])) == 1


def test_рекомендация_по_сильной_стороне_с_критиком():
    стороны = найти_сильные_стороны([стат("Материал и фактура", 4, 3)], УПОМИНАНИЯ)
    ш, клиент = шлюз(рек(), критик(5))
    итог = рекомендации_по_сильным_сторонам(ш, стороны, категория="одежда", всего_отзывов=10,
                                            принятые=["Указать замеры в карточке"])
    [п] = итог.accepted
    assert п.recommendation.kind == "strength" and п.recommendation.type == "карточка товара"
    assert п.recommendation.review_ids == ["r1", "r2", "r3"]
    генератор, проверка = клиент.calls[0][0].content, клиент.calls[1][0].content
    assert "Покупатели хвалят" in генератор and "75%" in генератор and "Проблема" not in генератор
    # критик видит действия, уже принятые по проблемам, и проверяет повторы с ними
    assert "хвалят характеристику" in проверка and "Указать замеры в карточке" in проверка


def test_доработка_идёт_тем_же_промптом_сильных_сторон():
    стороны = найти_сильные_стороны([стат("Материал и фактура", 4, 3)], УПОМИНАНИЯ)
    ш, клиент = шлюз(рек(), критик(2, "слишком общо"), рек("Материал не колется", n=2, action="Добавить в описание фразу «материал не колется»"),
                     критик(5))
    итог = рекомендации_по_сильным_сторонам(ш, стороны, категория="одежда", всего_отзывов=10)
    assert len(итог.accepted) == 1 and итог.stats["revisions"] == 1
    assert "Покупатели хвалят" in клиент.calls[2][0].content and "слишком общо" in клиент.calls[2][0].content


def test_выдуманная_цитата_и_сбой_генератора():
    стороны = найти_сильные_стороны([стат("Материал и фактура", 4, 3)], УПОМИНАНИЯ)
    ш, _ = шлюз(рек("Куртка самая тёплая на свете"))
    итог = рекомендации_по_сильным_сторонам(ш, стороны, категория="одежда", всего_отзывов=10)
    assert not итог.accepted and итог.problems_without_recommendation == ["Материал и фактура"]
    ш, _ = шлюз("не json")
    итог = рекомендации_по_сильным_сторонам(ш, стороны, категория="одежда", всего_отзывов=10)
    assert итог.stats["generator_failed"] == 1


def test_без_критика():
    стороны = найти_сильные_стороны([стат("Материал и фактура", 4, 3)], УПОМИНАНИЯ)
    ш, клиент = шлюз(рек())
    итог = рекомендации_по_сильным_сторонам(ш, стороны, категория="одежда", всего_отзывов=10,
                                            с_критиком=False)
    assert len(итог.accepted) == 1 and len(клиент.calls) == 1
