"""Тесты поиска персональных данных. Все контакты в тестах выдуманные."""
from review_agent.preprocess.pii import есть_пд, найти_пд, скрыть_пд


def test_скрываются_почта_телефоны_ссылки_номера():
    текст = ("Пишите test.user@example.com или звоните 89000000000, "
             "+7 (900) 000-00-00. Фото тут: http://example.com/abc "
             "заказ 12345678901234, ник @some_user")
    скрыто = скрыть_пд(текст)
    assert "example.com" not in скрыто
    assert "89000000000" not in скрыто and "000-00-00" not in скрыто
    assert "12345678901234" not in скрыто
    assert скрыто.count("[ТЕЛЕФОН]") == 2
    assert {"[EMAIL]", "[ССЫЛКА]", "[НОМЕР]", "[АККАУНТ]"} <= set(найти_пд(текст))


def test_размеры_цены_и_даты_не_персональные_данные():
    текст = "Размер S на 92-60-90, рост 170, цена 1500 руб, заказывала 15.06.2023"
    assert not есть_пд(текст)
    assert скрыть_пд(текст) == текст
