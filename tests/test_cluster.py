"""Тесты кластеризации по косинусному расстоянию."""
from review_agent.pipeline.cluster import ближайшие_к_центру, кластеризовать

ТРИ_ГРУППЫ = [[1, 0, 0], [0.99, 0.05, 0], [0.98, 0, 0.05],      # группа по оси x
              [0, 1, 0], [0.05, 0.99, 0],                         # группа по оси y
              [0, 0, 1]]                                          # одиночка


def test_находит_группы_без_заданного_числа_кластеров():
    assert [sorted(к) for к in кластеризовать(ТРИ_ГРУППЫ, 0.2)] == [[0, 1, 2], [3, 4], [5]]


def test_порог_управляет_укрупнением():
    assert len(кластеризовать(ТРИ_ГРУППЫ, 0.001)) == 6
    assert len(кластеризовать(ТРИ_ГРУППЫ, 2.0)) == 1


def test_пустой_и_одиночный_ввод():
    assert кластеризовать([]) == []
    assert кластеризовать([[1.0, 2.0]]) == [[0]]


def test_нулевой_вектор_не_ломает_расчёт():
    assert sorted(len(к) for к in кластеризовать([[0, 0], [1, 0], [1, 0.01]], 0.1)) == [1, 2]


def test_ближайшие_к_центру():
    векторы = [[1, 0], [0.9, 0.1], [0.5, 0.9]]
    выбранные = ближайшие_к_центру(векторы, [0, 1, 2], 2)
    assert len(выбранные) == 2 and 2 not in выбранные    # дальняя точка не попадает
